// Create context
const LanguageContext = createContext();

// Language provider component
export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState('en');
  const [direction, setDirection] = useState('ltr');

  // Load language from localStorage on initial render
  useEffect(() => {
    const savedLanguage = localStorage.getItem('language') || 'en';
    console.log(`[LanguageContext] Loading language from localStorage: ${savedLanguage}`);
    setLanguage(savedLanguage);
    setDirection(savedLanguage === 'ar' ? 'rtl' : 'ltr');
  }, []);

  // Change language function
  const changeLanguage = (newLanguage) => {
    console.log(`[LanguageContext] Changing language to: ${newLanguage}`);
    setLanguage(newLanguage);
    setDirection(newLanguage === 'ar' ? 'rtl' : 'ltr');
    localStorage.setItem('language', newLanguage);

    // Dispatch custom event for non-React components
    if (typeof window !== 'undefined') {
      window.dispatchEvent(new CustomEvent('languageChange', { detail: { language: newLanguage } }));
    }
  };

  // Translation function with variable substitution support
  const t = (key, variables = {}) => {
    // Debug logging
    if (process.env.NODE_ENV === 'development') {
      console.log(`[Translation] language: ${language}, key: ${key}, result: ${translations[language] && translations[language][key] ? translations[language][key] : key}`);
    }

    // Additional debug logging for specific keys
    if (key === 'dashboard' || key === 'todayOrders' || key === 'todayRevenue' || key === 'newCustomers' || key === 'avgOrderValue' || key === 'avgServiceTime' || key === 'addTable' || key === 'todaySummary' || key === 'orderChannels' || key === 'diningTables' || key === 'loadingOrders' || key === 'loadingTables' || key === 'noTablesAdded') {
      console.log(`[Translation Debug] Requested key: ${key}`);
      console.log(`[Translation Debug] Language: ${language}`);
      console.log(`[Translation Debug] Available translations:`, translations[language]);
      console.log(`[Translation Debug] Translation found:`, translations[language] && translations[language][key]);
      console.log(`[Translation Debug] Returning:`, translations[language] && translations[language][key] ? translations[language][key] : key);
    }

    let translation = translations[language] && translations[language][key] ? translations[language][key] : key;

    // Replace variables in the translation string
    Object.keys(variables).forEach(variable => {
      const regex = new RegExp(`\{${variable}\}`, 'g');
      translation = translation.replace(regex, variables[variable]);
    });

    return translation;
  };

  const value = {
    language,
    direction,
    changeLanguage,
    t
  };

  // Debug logging
  if (process.env.NODE_ENV === 'development') {
    console.log(`[LanguageContext] language: ${language}, direction: ${direction}`);
  }

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

// Custom hook to use language context
export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}

// Expose minimal API for non-React handlers (e.g., simple modals)
if (typeof window !== 'undefined') {
  // Will be updated by provider mount effect below
  window.LanguageContext = window.LanguageContext || {};
}

// Small helper component to bind the current context to window
export function LanguageWindowBridge() {
  const ctx = useContext(LanguageContext);
  useEffect(() => {
    if (typeof window !== 'undefined' && ctx) {
      window.LanguageContext = {
        changeLanguage: ctx.changeLanguage,
        language: ctx.language,
        t: ctx.t
      };
    }
  }, [ctx]);
  return null;
}